export const roleById = (id: RoleId): RoleDef => roles.find((role) => role.id === id) ?? roles[0];

export const permissionCount = (perms: RoleDef['permissions']) => ({
  full: PERMISSIONS.filter((p) => perms[p.key] === 'full').length,
  partial: PERMISSIONS.filter((p) => perms[p.key] === 'partial').length,
  none: PERMISSIONS.filter((p) => perms[p.key] === 'none').length,
});

/** Effective permission for a user = role matrix with per-user overrides applied. */
export const effectivePermission = (
  user: UserRecord,
  key: PermissionKey,
): 'full' | 'partial' | 'none' => user.permissions?.[key] ?? roleById(user.roleId).permissions[key];

